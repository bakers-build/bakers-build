// The primary tab row only: a secondary row is its own `<nav>` with its own
// current entry, and counting across both would hide a doubled marker.
function primaryTabLinks(page: Page) {
  return page.locator(PAGE_HEADER_ISLAND).locator('[data-tabs]').first().getByRole('link');
}

When('I view the page {int} pixels wide', async ({ page }, width: number) => {
  await page.setViewportSize({ width, height: 900 });
});

// Narrow viewports wrap the row instead of scrolling it. Asserted on the row and
// on every link box, not on the document width: a page body can overflow for
// reasons of its own, and that would be a different defect with a different owner.
Then('every tab fits within the viewport', async ({ page }) => {
  const links = primaryTabLinks(page);
  expect(await links.count()).toBeGreaterThan(1);
  const width = page.viewportSize()!.width;
  for (const link of await links.all()) {
    await expect(link).toBeVisible();
    const box = (await link.boundingBox())!;
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(width);
  }
  const overflow = await page
    .locator(PAGE_HEADER_ISLAND)
    .locator('[data-tabs]')
    .first()
    .evaluate((nav) => nav.scrollWidth - nav.clientWidth);
  expect(overflow).toBeLessThanOrEqual(0);
});

// The tab row sits on the header's bottom rule with no band between them. On a
// wrapped row the last line meets the rule, so the lowest link box is measured.
Then('the tab row rests on the header rule', async ({ page }) => {
  const links = primaryTabLinks(page);
  expect(await links.count()).toBeGreaterThan(1);
  const gap = await page.locator(PAGE_HEADER_ISLAND).locator('header').first().evaluate((header) => {
    const rule = header.getBoundingClientRect().bottom - parseFloat(getComputedStyle(header).borderBottomWidth);
    const lowest = Math.max(...Array.from(header.querySelectorAll('[data-tabs] a')).map((link) => link.getBoundingClientRect().bottom));
    return rule - lowest;
  });
  expect(Math.abs(gap)).toBeLessThanOrEqual(1);
});

Then('exactly one tab is marked as the current page', async ({ page }) => {
  await expect(primaryTabLinks(page).and(page.locator('[aria-current="page"]'))).toHaveCount(1);
});

// Native links in document order: Tab walks them one by one, and each shows a
// focus outline of its own, separate from the current-page underline. `solid`
// is the theme's `focus-visible:outline-2`; Chromium's own default is `auto`,
// so a weaker check would pass with the theme's ring removed.
Then('every tab can be reached with the Tab key and shows a focus ring', async ({ page }) => {
  const links = await primaryTabLinks(page).all();
  await links[0].focus();
  for (const [index, link] of links.entries()) {
    if (index) await page.keyboard.press('Tab');
    await expect(link).toBeFocused();
    expect(await link.evaluate((a) => getComputedStyle(a).outlineStyle)).toBe('solid');
  }
});

When('I activate the tab {string} with the keyboard', async ({ page }, tab: string) => {
  const link = page.locator(PAGE_HEADER_ISLAND).getByRole('link', { name: tab, exact: true });
  await link.focus();
  await page.keyboard.press('Enter');
  await expect(
    page.locator(PAGE_HEADER_ISLAND).getByRole('link', { name: tab, exact: true }),
  ).toHaveAttribute('aria-current', 'page', { timeout: 10000 });
});

Then('the address ends with {string}', async ({ page }, suffix: string) => {
  expect(new URL(page.url()).pathname.endsWith(suffix)).toBe(true);
});

Then('the document was not reloaded', async ({ page }) => {
  expect(await documentWasKept(page)).toBe(true);
});

// The failing side of the same detector. Everything this suite claims about
// AC 3 rests on the document mark, and a detector that cannot fail proves
// nothing — so one scenario drives it to `false` on purpose.
Then('the document was reloaded', async ({ page }) => {
  expect(await documentWasKept(page)).toBe(false);
});

/**
 * AC 3's request count, for the click currently under measurement.
 *
 * Module-level because a playwright-bdd step cannot hand state to the next
 * step. Safe because this scenario's steps run sequentially within one
 * scenario and the value is reset by the counting step itself, so two counted
 * clicks in one scenario each measure only their own click — independent of
 * how many workers the run uses.
 */
let countedRequests: { navigations: string[]; documents: string[] } | null = null;

function counted(): { navigations: string[]; documents: string[] } {
  if (countedRequests === null) {
    throw new Error('No counted click has run yet — use the counting click step first.');
  }
  return countedRequests;
}

// AC 3 has TWO halves and only one of them was asserted anywhere: "no full page
// load" (the document mark) and "in one HTTP request" (this). The click is made
// here rather than in a separate step so the listener covers exactly this click
// and nothing else.
//
// Only `document`, `xhr` and `fetch` count as navigations. The sub-resources the
// new markup pulls in — measured on 2026-09-01 as a throbber svg and an
// aggregated stylesheet — are assets, not navigations, and counting them would
// make the assertion track Drupal's asset aggregation instead of the mechanism.
When('I click the tab {string} and count the requests', async ({ page }, tab: string) => {
  const navigations: string[] = [];
  const documents: string[] = [];
  const listener = (request: { resourceType(): string; url(): string }) => {
    const type = request.resourceType();
    if (type === 'document') {
      documents.push(request.url());
      navigations.push(request.url());
    } else if (type === 'xhr' || type === 'fetch') {
      navigations.push(request.url());
    }
  };
  countedRequests = null;
  page.on('request', listener);
  try {
    await clickTab(page, tab);
  } finally {
    page.off('request', listener);
  }
  countedRequests = { navigations, documents };
});

Then('the tab change made exactly one navigation request', async () => {
  expect(counted().navigations).toHaveLength(1);
});

// The positive form of "no full page load", read off the network rather than off
// the document mark, so the two halves of AC 3 do not share a single mechanism.
Then('the tab change made no full document request', async () => {
  expect(counted().documents).toEqual([]);
});

// The rail's own current entry. Asserted through `aria-current`, which `nav`
// emits from `in_active_trail` — the same attribute the tab bar uses, so a
// scenario cannot pass by finding the tab bar's marker instead of the rail's.
Then('the rail marks {string} as current', async ({ page }, label: string) => {
  const current = page.locator(`${RAIL_ISLAND} [aria-current]`).filter({ hasText: label });
  await expect(current.first()).toBeAttached();
});

When('I click the rail entry {string}', async ({ page }, label: string) => {
  await page.locator(RAIL_ISLAND).getByRole('link', { name: label }).click();
  await expect(
    page.locator(`${RAIL_ISLAND} [aria-current]`).filter({ hasText: label }).first(),
  ).toBeAttached({ timeout: 10000 });
});

When('I open a themed workspace screen', async ({ page }) => {
  const collected: string[] = [];
  errors.set(page, collected);
  page.on('pageerror', (error) => collected.push(error.message));
  const response = await page.goto(workspaceScreenPath());
  expect(response?.status() ?? 0, 'The workspace screen did not render').toBeLessThan(400);
  // The bundle is deferred as a module, so its work is not done at `load`.
  await page.waitForLoadState('networkidle');
});

Then('the page heading is {string}', async ({ page }, heading: string) => {
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(heading, { timeout: 10000 });
});

Then('the document title names the site once', async ({ page }) => {
  const site = php('print \\Drupal::config("system.site")->get("name");');
  await expect.poll(async () => (await page.title()).split(' | ').filter((part) => part === site).length).toBe(1);
  await expect(page).toHaveTitle(new RegExp(` \\| ${site}$`));
});

Then('the document title names {string}', async ({ page }, name: string) => {
  await expect(page).toHaveTitle(new RegExp(`(^|\\W)${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\W|$)`), { timeout: 10000 });
});

/**
 * The rail does NOT mark an entry as current.
 *
 * THE NEGATIVE HALF OF `the rail marks {string} as current`. The ticket
 * list needed it first: `BbMenuSource` compares GENERATED URLS for exact
 * equality, and `/{workspace}/tickets/all` shares its first two segments with
 * the entry's own `/{workspace}/tickets`. A prefix comparison would mark My
 * work on the find-a-ticket table, and only a negative can see that.
 *
 * The rail is asserted PRESENT first, so a screen that rendered no rail at all
 * cannot satisfy "the entry is not marked".
 */
Then('the rail does not mark {string} as current', async ({ page }, label: string) => {
  const target = active(page);
  await expect(target.locator(RAIL_ISLAND)).toBeAttached();
  await expect(
    target.locator(RAIL_ISLAND).getByRole('link', { name: label }),
  ).toBeAttached();
  await expect(
    target.locator(`${RAIL_ISLAND} [aria-current]`).filter({ hasText: label }),
  ).toHaveCount(0);
});

// The browser side of HX-Trigger: htmx dispatches the announced event, which
// bubbles to the document; every island subscribed to it fetches itself.
When('the page is announced the island event {string}', async ({ page }, name: string) => {
  const refreshed = page.waitForResponse((r) => r.request().method() === 'GET' && r.request().headers()['hx-boosted'] === 'true');
  await page.evaluate((event) => document.body.dispatchEvent(new Event(event, { bubbles: true })), name);
  expect((await refreshed).status()).toBe(200);
});
