/**
 * Any themed workspace screen will do; the slug is resolved rather than
 * hardcoded, the way the create-dialog steps already resolve theirs, because a
 * freshly provisioned world does not promise a particular one.
 */
function workspaceScreenPath(): string {
  const slug = php(
    '$w = current(\\Drupal::entityTypeManager()->getStorage("bb_workspace")' +
      '->loadByProperties(["slug" => "bakers"])); print $w ? $w->get("slug")->value : "";',
  );
  if (!slug) {
    throw new Error('No bb_workspace with slug "bakers" exists in the seeded world.');
  }
  return `/${slug}/projects`;
}

/**
 * The public URL of a team, resolved by label rather than hardcoded.
 *
 * `/bakers/team/1` would couple every scenario to the seed's insertion order, and
 * the seed is regenerated by `ddev init --provider recipe-test`. Asking Drupal
 * for the entity's own toUrl() also means the scenario keeps working through the
 * workspace path processor, which rewrites `/bakers/…` to `/_workspace/bakers/…`
 * inbound and back outbound (spec F37).
 */
function teamUrl(label: string): string {
  // Shell quoting, both halves observed rather than anticipated. Inside DOUBLE
  // quotes the shell expands `$ids` before drush ever sees the snippet, which
  // is how the first version silently became `if (!) {`. Inside SINGLE quotes
  // it expands nothing, so a PHP variable survives untouched and must NOT be
  // backslash-escaped — the backslash would reach PHP and be a parse error.
  // The single-quoted form is therefore the one to use, and its only rule is
  // that the snippet contains no single quote of its own: every PHP string
  // below is double-quoted for that reason.
  const safe = label.replace(/["'\\$]/g, '');
  const php =
    'print (($e = current(\\Drupal::entityTypeManager()->getStorage("bb_team")' +
    `->loadByProperties(["name" => "${safe}"]))) ? $e->toUrl()->toString() : "");`;
  const url = Drush.exec(`ev '${php}'`).trim();
  if (!url) {
    throw new Error(`No bb_team named "${label}" exists in the seeded world.`);
  }
  return url;
}

// Registered once, under Given. playwright-bdd matches a step by its TEXT and
// not by its keyword, so a second registration under When is a duplicate
// definition and an error — the feature file is free to write either.
Given('I visit the team {string}', async ({ page }, label: string) => {
  await page.goto(teamUrl(label));
  await markDocument(page);
});

When('I visit the team {string} tab {string}', async ({ page }, label: string, tab: string) => {
  await page.goto(`${teamUrl(label)}/${tab.toLowerCase()}`);
  await markDocument(page);
});

/**
 * Clicks a tab and waits for the swap to land.
 *
 * The swap is what is being tested, so this waits for the island to carry the
 * new tab rather than for a network event: a boosted navigation fires no
 * navigation event, and waiting for one would time out on success.
 */
async function clickTab(page: Page, tab: string): Promise<void> {
  // Scoped to the content island, exactly like the assertion below it. The tab
  // bar lives INSIDE that island — which is the whole of spec D3, the row rides
  // along in the swap — so this is the correct scope and not a narrowing. A
  // page-wide lookup would also match a rail entry: today's seed has no team
  // named after a tab, but a team called "Runs" would silently make this click
  // the rail and the scenario would assert against the wrong navigation.
  await page
    .locator(PAGE_HEADER_ISLAND)
    .getByRole('link', { name: tab, exact: true })
    .click();
  await expect(
    page.locator(PAGE_HEADER_ISLAND).getByRole('link', { name: tab, exact: true }),
  ).toHaveAttribute('aria-current', /page|true/, { timeout: 10000 });
}

When('I click the tab {string}', async ({ page }, tab: string) => {
  await clickTab(page, tab);
});

When('I reload the page', async ({ page }) => {
  await page.reload();
});

