// BB-419 — ONE member surface, asserted live on BOTH screens.
//
// The PHP coverage proves the two screens render the same classes. It cannot
// prove the thing that made this an island in the first place: that adding or
// removing a member re-renders only that face and keeps the document. An island
// is a client-side mechanism, so only a browser can see it — and it has to be
// seen on both call sites, or "one component" is a claim about source code
// rather than about the product.
//
// EVERY NAVIGATING SCENARIO CLICKS TWICE. A declaration lost in a swap still
// survives the first click (BB-408's measured defect), so a one-click scenario
// cannot see it. The remove scenarios here click a tab AFTER the mutation, which
// lands on the fragment the REMOVE handed back rather than one a navigation
// produced — one swap deeper than any navigation-only scenario reaches.
import { Given, When, Then } from '../../bdd.fixtures';
import { Drush } from '../../support/drush';
import { expect } from '@playwright/test';
import { MEMBERS_ISLAND, markDocument, uidOf } from '../../support/shell';

/**
 * One row of the roster table. Direct children only, so the rows of a role
 * picker's own option list are never counted as members.
 */
const MEMBER_ITEM = `${MEMBERS_ISLAND} table > tbody > tr`;

/**
 * The public URL of a project, resolved by label rather than hardcoded.
 *
 * `/bakers/project/1` would couple every scenario to the seed's insertion order,
 * and the seed is regenerated by `ddev init --provider recipe-test`. Asking
 * Drupal for the entity's own toUrl() also keeps the scenario working through
 * the workspace path processor, which rewrites `/bakers/…` to `/_workspace/bakers/…`
 * inbound and back outbound.
 *
 * The shell quoting is the team steps' rule, for the team steps' reason: the
 * snippet is SINGLE-quoted so `$e` reaches PHP unexpanded, and it therefore
 * contains no single quote of its own.
 */
function projectUrl(label: string): string {
  const safe = label.replace(/["'\\$]/g, '');
  const php =
    'print (($e = current(\\Drupal::entityTypeManager()->getStorage("bb_project")' +
    `->loadByProperties(["name" => "${safe}"]))) ? $e->toUrl()->toString() : "");`;
  const url = Drush.exec(`ev '${php}'`).trim();
  if (!url) {
    throw new Error(`No bb_project named "${label}" exists in the seeded world.`);
  }
  return url;
}

/**
 * WHO is in the list, as a sorted set of uids — not how many rows it has.
 *
 * THE COUNT WAS THE HOLE. BB-419's remove control shipped removing the WRONG
 * member and every browser assertion stayed green, because add-then-remove
 * returns the list to its original LENGTH whichever member was actually
 * deleted. Identity is the only assertion that can tell the two apart, and the
 * remove control publishes `data-bakers-member-uid` precisely so a caller can
 * read it.
 */
async function memberUids(page: import('@playwright/test').Page): Promise<string[]> {
  const uids = await page
    .locator(`${MEMBERS_ISLAND} [data-bakers-member-uid]`)
    .evaluateAll((nodes) => nodes.map((n) => n.getAttribute('data-bakers-member-uid') ?? ''));
  return uids.filter((uid) => uid !== '').sort();
}

/**
 * Removes one member, and waits on the submit's OWN response.
 *
 * Not on a duration: an island submit answers with a fragment and fires no
 * navigation event, so there is no navigation to await — but there is a POST,
 * and its response is the moment the server has decided. A fixed sleep would
 * let the row-count assertion after it be satisfied before the request had
 * happened at all, which is the defect the add step's own comment records.
 *
 * THE ROW IS ADDRESSED BY UID, NOT BY THE ACCOUNT'S VISIBLE NAME. Measured
 * rather than assumed: the first version of this step filtered rows by the name
 * in the "Label (id)" string, and it matched nothing — uid 1 is `admin` on a
 * stock install but `placeholder-for-uid-1` on a `--provider recipe-test` world,
 * the same trap the add step's precondition already records. The control
 * publishes `data-bakers-member-uid` for exactly this, which is also why every
 * row's button can share one label without becoming unaddressable.
 */
When('I remove the member {string}', async ({ page }, value: string) => {
  const uid = uidOf(value);
  const answered = page.waitForResponse(
    (response) => response.request().method() === 'POST',
    { timeout: 15000 },
  );
  await page.locator(`${MEMBERS_ISLAND} [data-bakers-member-uid="${uid}"]`).first().click();
  await answered;
});

/**
 * The remove control's accessible name, which is what stands in for a confirm.
 *
 * MATCHED AS A SUBSTRING SINCE BB-435, because the name is now a SENTENCE
 * naming the effect rather than a label naming the group: "Remove <person> from
 * the <group>. Revokes their access." on a rights-granting surface, and "… A
 * <group> membership grants no permissions, so no access is revoked." where the
 * group grants none. A scenario asserts the clause it cares about instead of
 * restating a person's name it did not choose.
 *
 * The per-group-type difference the shared surface keeps is therefore asserted
 * per screen, in both directions: each feature says which clause is present AND
 * that the other one is not.
 */
Then('the remove control names {string}', async ({ page }, text: string) => {
  await expect(
    page.locator(`${MEMBERS_ISLAND} [aria-label*="${text}"]`).first(),
  ).toBeAttached();
});

/**
 * No remove control on this face names the given text.
 *
 * The negative half of the naming pair, and it is what makes the pair mean
 * something: without it a control that said BOTH things, or the wrong thing on
 * both screens, would still satisfy the positive assertion on one of them.
 */
Then('no remove control names {string}', async ({ page }, text: string) => {
  await expect(page.locator(`${MEMBERS_ISLAND} [aria-label*="${text}"]`)).toHaveCount(0);
});

/**
 * The row count remembered before a mutation, so a delta can be asserted.
 *
 * WHY A DELTA AND NOT AN ABSOLUTE COUNT. The team feature can hardcode `3` and
 * `4` because that team's crew is a fixture written for it. The project's
 * membership rows are not: they come from the seed's og_membership fixtures,
 * which exist to prove the read scope rather than to be counted here, and a
 * later ticket adding one would break this scenario for a reason that has
 * nothing to do with the surface it tests. The delta is what this scenario is
 * actually about — one add makes one row, one remove takes one away.
 */
let notedRowCount: number | null = null;

/**
 * WHO was in the list before the mutation, alongside how many rows it had.
 *
 * Both, because they answer different questions and only one of them can catch
 * a wrong removal. The add half genuinely is about a count — one add makes one
 * row — while the remove half has to be about identity.
 */
let notedMembers: string[] | null = null;

Given('I note the members list', async ({ page }) => {
  notedRowCount = await page.locator(MEMBER_ITEM).count();
  notedMembers = await memberUids(page);
});

Then('the members list has one more row', async ({ page }) => {
  if (notedRowCount === null) {
    throw new Error('Note the members list before asserting a change to it.');
  }
  await expect(page.locator(MEMBER_ITEM)).toHaveCount(notedRowCount + 1);
});

/**
 * Back to the noted MEMBERS — the assertion after an add-then-remove pair.
 *
 * THIS REPLACES A ROW COUNT, and the replacement is the point rather than a
 * tidy-up. `the members list is back to the length I noted` was true whichever
 * member the remove actually deleted, because add-then-remove restores the
 * length either way — so both this scenario and its project twin ran straight
 * THROUGH a control that removed the wrong member and reported green. Comparing
 * the uid set says the added member went and nobody else did, which is the
 * claim the scenario was always making.
 *
 * NOT "one fewer than noted": the set is noted BEFORE the add, so undoing that
 * add returns the list to exactly the noted set.
 */
Then('the members list is back to the members I noted', async ({ page }) => {
  if (notedMembers === null) {
    throw new Error('Note the members list before asserting a change to it.');
  }
  await expect.poll(() => memberUids(page)).toEqual(notedMembers);
});

/**
 * The removed member is really gone, named rather than counted.
 *
 * Says out loud what the set comparison above implies, so a failure names the
 * account instead of printing two lists for a reader to diff.
 */
Then('the members list has no member {string}', async ({ page }, value: string) => {
  await expect(
    page.locator(`${MEMBERS_ISLAND} [data-bakers-member-uid="${uidOf(value)}"]`),
  ).toHaveCount(0);
});

/**
 * One member's item, addressed by the uid its remove control publishes.
 *
 * `data-bakers-member-uid` is the documented machine handle, and it is the only
 * usable one: uid 1 is `admin` on a stock install and `placeholder-for-uid-1`
 * on a `--provider recipe-test` world, so a step matching the visible name
 * matches nothing there.
 */
function memberItem(page: import('@playwright/test').Page, value: string) {
  return page
    .locator(MEMBER_ITEM)
    .filter({ has: page.locator(`[data-bakers-member-uid="${uidOf(value)}"]`) })
    .first();
}

/**
 * Picks a role on one member's item, and waits on the submit's OWN response.
 *
 * THE PICK IS THE WRITE, so there is no save button to press afterwards and
 * nothing to confirm — the option row IS a named submit trigger of the enclosing
 * form. That is why this step clicks the row and then waits for a POST: an
 * island submit answers with a fragment and fires no navigation event, so there
 * is no navigation to await, but there is a request whose response is the moment
 * the server has decided. A fixed sleep would let the assertion after it pass
 * before the write had happened at all.
 *
 * THE PANEL IS OPENED FIRST because the picker is a disclosure: the rows live
 * inside a `hidden` panel until the trigger is pressed, and clicking a hidden
 * element is not something a human can do either.
 */
When(
  'I pick the role {string} for the member {string}',
  async ({ page }, role: string, value: string) => {
    const item = memberItem(page, value);
    await item.locator('[data-option-picker-trigger]').first().click();
    const answered = page.waitForResponse(
      (response) => response.request().method() === 'POST',
      { timeout: 15000 },
    );
    await item.locator(`button[value="${role}"]`).first().click();
    await answered;
  },
);

/**
 * The role one member's item SHOWS, which after a reload is the stored one.
 *
 * THE RELOAD IS THE CRITERION and it belongs in the scenario rather than here:
 * a swap that renders the new value proves nothing about storage, because the
 * fragment could have been built from the submitted value. This step only reads
 * what the item displays; the scenario decides whether it is reading a fresh
 * document.
 */
Then(
  'the member {string} shows the role {string}',
  async ({ page }, value: string, role: string) => {
    await expect
      .poll(async () => (await memberItem(page, value).innerText()).replace(/\s+/g, ' '))
      .toContain(role);
  },
);

/** The roster is a table whose header row names its columns, in order. */
Then('the members table has the columns {string}', async ({ page }, columns: string) => {
  const table = page.locator(`${MEMBERS_ISLAND} table`).first();
  const names = columns.split(',').map((name) => name.trim());
  await expect(table.getByRole('columnheader').filter({ hasText: /\S/ })).toHaveText(names);
  await expect(page.locator(MEMBER_ITEM).first()).toBeVisible();
});

Then(
  'the member {string} shows their initial, role, joined date and remove control in their row',
  async ({ page }, account: string) => {
    const item = memberItem(page, account);
    await expect(item).toBeVisible();
    await expect(item.locator('[data-person-mark]')).toHaveText(account.charAt(0).toUpperCase());
    await expect(item.locator('[data-option-picker-trigger]').first()).toBeVisible();
    await expect(item.getByText(/^\d{1,2} [A-Z][a-z]{2}( \d{4})?$/)).toBeVisible();
    await expect(item.locator(`[data-bakers-member-uid="${uidOf(account)}"]`).first()).toBeVisible();
  },
);
