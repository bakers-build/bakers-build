#!/usr/bin/env bash
# =============================================================================
# teardown-test-project.sh — give back everything setup-test-project.sh created.
#
#   scripts/teardown-test-project.sh [--project <name>] [--keep-clone]
#
#     --project <name>  the bb_project whose tickets and runs are purged. It must
#                       match the name `setup` ran with, because the purge is scoped
#                       to the conductor whose conductor_id is composed FROM it — a
#                       different name identifies a different conductor and purges
#                       nothing. Default: bakers-e2e-project.
#     --keep-clone      reclaim the DDEV projects and the control-plane entities but
#                       LEAVE the clone at workspaces/bakers-playground and its local
#                       origin workspaces/bakers-playground.git on disk. For
#                       driving another run against the same generated configs
#                       without paying for a fresh clone and a cold `ddev start`.
#
# WHAT IT DOES NOT TOUCH, deliberately:
#
#   * the CONTROL-PLANE DDEV. It is the checkout's own development environment;
#     reclaiming it because a test finished would be a surprise. Use `ddev delete`
#     yourself if you want that.
#   * the world's RECIPE FIXTURES. The purge is scoped to the conductor carrying
#     this machine's own conductor_id, so `GL-E2E-CONDUCTOR` and every fixture ticket
#     CI depends on survive.
#
# AND IT REFUSES RATHER THAN GUESSES, twice over:
#
#   * with no conductor matching the conductor_id there is no marker distinguishing
#     this machine's tickets from the world's fixtures, so NOTHING is deleted and
#     the count that was kept is reported;
#   * no `ddev delete` runs unless an explicitly named, registered `bakers-pg-`
#     project has exactly the owned fixture directory as its application root.
#     An overlay alone does not register a nested project: an unnamed deletion
#     can resolve to the parent control plane instead.
#
# THE LOCAL ORDER IS HARD-WON, not stylistic:
#
#   conductor stop -> entity purge -> per-worktree `ddev delete`
#   -> workspace `ddev delete` -> `git worktree prune` -> rm -rf
#
# The conductor is stopped BEFORE the clone is deleted because its config lives in
# that clone: `bakers oven stop` reads `<clone>/.bakers/conductor.config.js` to
# learn which conductor to signal, so a clone removed first leaves a running
# process nothing can address. It is best-effort — teardown must not fail because
# the conductor was already gone.
#
# WHAT `stop` NO LONGER DOES — corrected here rather than inherited from the
# predecessor script: `bakers oven start` opens a herdr workspace
# `bakers-conductor:<id>`, and BB-232 deliberately removed the tab-killing from
# `stop` and `stop --now` (a signal reaches the process wherever it lives, and a
# conductor started under systemd has no tab at all). That workspace therefore
# SURVIVES teardown and reappears on the next herdr layout. Closing it is left as
# one manual step on purpose: the workspace id is not derivable from anything
# teardown reliably holds, and guessing it means closing somebody else's work.
#
#   herdr workspace list                  # find the bakers-conductor:<id> entry
#   herdr workspace close <workspace_id>
# =============================================================================
set -euo pipefail

PROJECT='bakers-e2e-project'
WORKSPACE_RELPATH='workspaces/bakers-playground'
KEEP_CLONE='no'

usage() {
  awk 'NR <= 2 { next } /^# =+$/ { exit } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "$0"
}
die() { echo "ERROR: $*" >&2; exit 1; }
step() { echo; echo "== $*"; }
say() { echo "   $*"; }

# See setup-test-project.sh's php_str: identical by intent, because both scripts
# interpolate into single-quoted PHP and one escaper per script beats a shared
# library neither would otherwise need.
php_str() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e "s/'/\\\\'/g"
}

# Resolve by name as well as directory: only named describe requires the project
# to be registered, and its application root proves which checkout owns it.
# An optional expected name pins the workspace to the one generated by setup.
harness_ddev_name() {
  local dir name
  dir="${1%/}"
  [ "$(cd "${dir}" && pwd -P)" = "${dir}" ] || return 1
  name="${2:-}"
  if [ -z "${name}" ]; then
    name="$( ( cd "${dir}" && ddev describe -j 2>/dev/null ) | jq -r '.raw.name // empty' 2>/dev/null)" || return 1
  fi
  case "${name}" in bakers-pg-*) ;; *) return 1 ;; esac
  ddev describe "${name}" -j 2>/dev/null | jq -er \
    --arg name "${name}" --arg dir "${dir}" \
    'select(.raw.name == $name and .raw.approot == $dir) | .raw.name' 2>/dev/null
}

while [ $# -gt 0 ]; do
  case "$1" in
    --project) PROJECT="${2:?--project needs a value}"; shift 2 ;;
    --keep-clone) KEEP_CLONE='yes'; shift ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument '$1' (try --help)" ;;
  esac
done

# The same door check setup applies, for the same reason and so the two cannot
# disagree about which project names are representable.
case "${PROJECT}" in
  '' | *[!A-Za-z0-9._-]*)
    die "--project '${PROJECT}' must be a bb_project machine name
       ([A-Za-z0-9._-] only)" ;;
esac

for tool in git ddev jq node; do
  command -v "$tool" >/dev/null || die "'$tool' is required but not on PATH"
done

ROOT="$(git rev-parse --show-toplevel)"
WORKSPACE="${ROOT}/${WORKSPACE_RELPATH}"
BB_BIN="${ROOT}/bakers-cli/bin/bakers"
WS_DDEV="bakers-pg-$(printf '%s' "${WORKSPACE}" | sha1sum | cut -c1-8)"

# --- Guards, protecting the thing teardown must never reclaim. ----------------
[ "${WORKSPACE}" != "${ROOT}" ] \
  || die "the workspace path resolves to the checkout itself — refusing"
[ ! -x "${WORKSPACE}/bakers-cli/bin/bakers" ] \
  || die "${WORKSPACE} looks like a bakers checkout, not the work workspace — refusing"

# -----------------------------------------------------------------------------
step "1. stop the conductor before reclaiming its data or environment"
# Its config and control-plane connection must still exist when stop runs.
if [ -f "${WORKSPACE}/.bakers/conductor.config.js" ] && [ -x "${BB_BIN}" ]; then
  ( cd "${WORKSPACE}" && "${BB_BIN}" oven stop --now ) || true
  say "conductor stopped (best-effort)"
fi

# -----------------------------------------------------------------------------
step "2. the control-plane entities — scoped to this machine's conductor"
# -----------------------------------------------------------------------------
# Composed exactly as setup composes it, so the two cannot disagree about which
# conductor's work is being reclaimed. See setup step 7 for why the machine context
# is imported rather than pattern-matched.
machine_identity="$(MC="${HOME}/.bakers/machine.config.js" node -e '
  const p = process.env.MC;
  import("node:fs").then(async (fs) => {
    if (!fs.existsSync(p)) return process.stdout.write("\t");
    try {
      const d = (await import("file://" + p)).default ?? {};
      process.stdout.write(`${d.user_id ?? ""}\t${d.machine_id ?? ""}`);
    } catch { process.stdout.write("\t"); }
  });' 2>/dev/null || printf '\t')"
MACHINE_USER="$(printf '%s' "${machine_identity}" | cut -f1)"
MACHINE_HOST="$(printf '%s' "${machine_identity}" | cut -f2)"
if [ -z "${MACHINE_HOST}" ]; then
  MACHINE_HOST="$( ( cd "${ROOT}" && ddev describe -j 2>/dev/null ) | jq -r '.raw.name // ""')"
fi
if [ -n "${MACHINE_USER}" ]; then
  MACHINE_ID="${MACHINE_USER}-${MACHINE_HOST}-${PROJECT}"
else
  MACHINE_ID="${MACHINE_HOST}-${PROJECT}"
fi
say "conductor_id: ${MACHINE_ID}"

# Pre-escaped for the PHP snippet below — see php_str. The machine context is a JS
# file the operator owns, so neither of these two values is constrained the way
# --project is.
Q_PROJECT="$(php_str "${PROJECT}")"
Q_MACHINE_ID="$(php_str "${MACHINE_ID}")"

# Deleted through `ddev drush` in the control-plane checkout, which is why this
# cannot reach dev2 or prod even if a config said otherwise — and it runs as the
# Drupal root user, so no access handler gates the delete.
#
# A ticket counts as this machine's when EITHER it carries the conductor on
# `conductor_id` OR a run of it does. The second half closes the hole a detached
# ticket would open: `conductor_id` is cleared whenever a run is released, so
# keying on it alone would orphan every ticket the conductor has already finished.
if ( cd "${ROOT}" && ddev describe -j >/dev/null 2>&1 ); then
  # drush is noisy on stderr, so it is captured rather than silenced: discarding it
  # left the warning below naming no cause at all, which is the least useful thing
  # a failed destructive step can do.
  purge_err="$(mktemp)"
  if ( cd "${ROOT}" && ddev drush php:eval "
    \$etm = \\Drupal::entityTypeManager();
    \$ts = \$etm->getStorage('bb_ticket');
    \$rs = \$etm->getStorage('bb_run');
    \$ps = \$etm->getStorage('bb_project')->loadByProperties(['name' => '${Q_PROJECT}']);
    \$project = reset(\$ps);
    if (!\$project) {
      print \"nothing to purge: no bb_project named '${Q_PROJECT}'\" . PHP_EOL;
      return;
    }
    \$cs = \$etm->getStorage('bb_conductor')->loadByProperties(['conductor_id' => '${Q_MACHINE_ID}']);
    \$conductor = reset(\$cs);
    \$in_project = \$ts->loadByProperties(['project_id' => \$project->id()]);
    if (!\$conductor) {
      print 'refusing to purge: no bb_conductor with conductor_id ' .
        \"'${Q_MACHINE_ID}' — nothing identifiable to delete, kept \" .
        count(\$in_project) . ' ticket(s)' . PHP_EOL;
      return;
    }
    \$mine = [];
    foreach (\$in_project as \$ticket) {
      \$owned = (string) \$ticket->get('conductor_id')->target_id === (string) \$conductor->id();
      if (!\$owned) {
        \$owned = (bool) \$rs->getQuery()->accessCheck(FALSE)
          ->condition('ticket_id', \$ticket->id())
          ->condition('conductor_id', \$conductor->id())
          ->execute();
      }
      if (\$owned) { \$mine[\$ticket->id()] = \$ticket; }
    }
    foreach (\$mine as \$ticket) {
      \$run_ids = \$rs->getQuery()->accessCheck(FALSE)
        ->condition('ticket_id', \$ticket->id())->execute();
      \$runs = \$rs->loadMultiple(\$run_ids);
      foreach (\$runs as \$run) { \$run->delete(); }
      print 'deleted ' . (string) \$ticket->get('identifier')->value .
        ' (' . (string) \$ticket->get('state')->value . ', ' . count(\$runs) . ' run(s))' . PHP_EOL;
      \$ticket->delete();
    }
    print 'purged ' . count(\$mine) . ' ticket(s); kept ' .
      (count(\$in_project) - count(\$mine)) . ' fixture ticket(s)' . PHP_EOL;
" 2>"${purge_err}" | grep -Ev '^\s*$' | sed 's/^/   /' ); then
    :
  else
    say "WARNING: the control-plane purge failed — the entities are still there"
    sed 's/^/   | /' <"${purge_err}" >&2
  fi
  rm -f "${purge_err}"
else
  say "the control-plane DDEV is not up — skipping the entity purge"
fi

# -----------------------------------------------------------------------------
step "3. the local half"
# -----------------------------------------------------------------------------
# The local bare origin setup seeds from tests/fixtures/bakers-playground.
FIXTURE_ORIGIN="${WORKSPACE}.git"
if [ ! -d "${WORKSPACE}" ]; then
  say "no workspace at ${WORKSPACE} — nothing local to reclaim"
  [ "${KEEP_CLONE}" = 'yes' ] || rm -rf "${FIXTURE_ORIGIN}"
  echo; echo "teardown complete"; exit 0
fi

# The per-ticket worktrees' own DDEV projects, before their parent's. The herdr
# workspace puts them in `<clone>/.bakers-worktrees/<branch>`; the sibling
# `<clone>-worktrees` is swept too, in case an older run left one there.
for wt_root in "${WORKSPACE}/.bakers-worktrees" "${WORKSPACE}-worktrees"; do
  [ -d "${wt_root}" ] || continue
  while IFS= read -r -d '' ddev_dir; do
    worktree="${ddev_dir%/.ddev}"
    # Guarded exactly like its sibling below, and for the same reason: a per-ticket
    # worktree carries the fixture's TRACKED .ddev/config.yaml and gets no overlay
    # of its own unless something ran `setup-worktree.mjs` there, so the name it would be
    # deleted under can belong to an unrelated checkout.
    if wt_ddev="$(harness_ddev_name "${worktree}")"; then
      say "reclaiming worktree ddev project '${wt_ddev}' in ${worktree}"
      ddev delete -Oy "${wt_ddev}" || true
    else
      say "WARNING: no registered 'bakers-pg-' project owns ${worktree} — leaving DDEV alone"
    fi
  done < <(find "${wt_root}" -type d -name .ddev -prune -print0)
done

# The workspace's own DDEV project, but ONLY under the name setup gave it. Without
# that check a clone whose overlay went missing would be deleted under its
# COMMITTED `name:` — which is identical in every checkout of the fixture repo, so
# a teardown here would reclaim another worktree's DDEV project.
OVERLAY="${WORKSPACE}/.ddev/config.worktree.yaml"
if [ -f "${OVERLAY}" ] && grep -qxF "name: ${WS_DDEV}" "${OVERLAY}"; then
  if ws_ddev="$(harness_ddev_name "${WORKSPACE}" "${WS_DDEV}")"; then
    say "reclaiming workspace ddev project '${ws_ddev}'"
    ddev delete -Oy "${ws_ddev}" || true
  else
    say "WARNING: '${WS_DDEV}' is not registered at ${WORKSPACE} — leaving DDEV alone"
  fi
elif [ -d "${WORKSPACE}/.ddev" ]; then
  say "WARNING: ${OVERLAY} does not name '${WS_DDEV}' — leaving the ddev project"
  say "         alone rather than deleting one this script may not own"
fi

if [ "${KEEP_CLONE}" = 'yes' ]; then
  say "--keep-clone: leaving ${WORKSPACE} in place"
else
  [ -d "${WORKSPACE}/.git" ] && { git -C "${WORKSPACE}" worktree prune || true; }
  rm -rf "${WORKSPACE}-worktrees" "${WORKSPACE}" "${FIXTURE_ORIGIN}"
  say "${WORKSPACE} and ${FIXTURE_ORIGIN} are gone"
fi

echo
echo "teardown complete — the control-plane DDEV and the world's recipe fixtures are untouched"
